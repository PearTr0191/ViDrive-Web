// ─── Context ────────────────────────────────────────────────────────────────
interface I18nContextType {
  t: (key: string, params?: Record<string, string | number>) => string
  locale: Locale
  setLocale: (locale: Locale) => void
}

const I18nContext = createContext<I18nContextType | null>(null)

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (initialLocale) return initialLocale
    if (typeof localStorage !== 'undefined') {
      try {
        const saved = localStorage.getItem('vidrive-locale')
        if (saved === 'vi' || saved === 'en') return saved
      } catch { /* storage unavailable */ }
    }
    return DEFAULT_LOCALE
  })

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    if (typeof localStorage !== 'undefined') {
      try {
        localStorage.setItem('vidrive-locale', next)
      } catch { /* storage full or unavailable — best-effort */ }
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const t = useCallback(
    (key: string, params?: Record<string, string | number>): string => {
      let text = translations[locale]?.[key] ?? translations.en?.[key] ?? key
      if (params) {
        text = text.replace(/\{(\w+)\}/g, (match, p1) => {
          return p1 in params ? String(params[p1]) : match
        })
      }
      return text
    },
    [locale],
  )

  return (
    <I18nContext.Provider value={{ t, locale, setLocale }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n(): I18nContextType {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
